/**
 * Generates frontend/lib/data/dsa-interview-questions.ts
 * 11 categories × 50 questions (20 Easy, 20 Medium, 10 Hard)
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(__dirname, "dsa-bank-data.json");
const OUT = path.join(__dirname, "../lib/data/dsa-interview-questions.ts");

const TITLE_OVERRIDES = {
  "two-sum": "Two Sum",
  "3sum": "3Sum",
  "4sum": "4Sum",
  "3sum-closest": "3Sum Closest",
  "kth-largest-element-in-an-array": "Kth Largest Element in an Array",
  "lru-cache": "LRU Cache",
  "lfu-cache": "LFU Cache",
  "ipo": "IPO",
  "diameter-of-binary-tree": "Diameter of Binary Tree",
  "powx-n": "Pow(x, n)",
  "sqrtx": "Sqrt(x)",
  "ugly-number-iii": "Ugly Number III"
};

function slugToTitle(slug) {
  if (TITLE_OVERRIDES[slug]) return TITLE_OVERRIDES[slug];
  return slug
    .split("-")
    .map((part) => {
      if (part === "ii") return "II";
      if (part === "iii") return "III";
      if (part === "iv") return "IV";
      if (part === "bst") return "BST";
      if (part === "dp") return "DP";
      return part.charAt(0).toUpperCase() + part.slice(1);
    })
    .join(" ")
    .replace(/\bOf\b/g, "of")
    .replace(/\bAnd\b/g, "and")
    .replace(/\bOr\b/g, "or")
    .replace(/\bIn\b/g, "in")
    .replace(/\bTo\b/g, "to")
    .replace(/\bA\b/g, "a")
    .replace(/\bAn\b/g, "an")
    .replace(/\bThe\b/g, "the")
    .replace(/^./, (c) => c.toUpperCase());
}

function normalizeEntry(entry, difficulty) {
  const [slug, tag] = Array.isArray(entry) ? entry : [entry];
  return {
    title: slugToTitle(slug),
    difficulty,
    url: `https://leetcode.com/problems/${slug}/`,
    tag: tag || undefined,
    slug
  };
}

function buildCategory(difficultyBuckets) {
  const out = [];
  for (const diff of ["Easy", "Medium", "Hard"]) {
    for (const entry of difficultyBuckets[diff] || []) {
      out.push(normalizeEntry(entry, diff));
    }
  }
  return out;
}

const BANK = JSON.parse(fs.readFileSync(DATA, "utf8"));
const usedSlugs = new Set();
const dsaQuestions = {};

for (const [key, buckets] of Object.entries(BANK)) {
  const questions = buildCategory(buckets);
  const counts = { Easy: 0, Medium: 0, Hard: 0 };
  const seen = new Set();

  for (const q of questions) {
    counts[q.difficulty]++;
    if (seen.has(q.slug)) throw new Error(`Duplicate in ${key}: ${q.slug}`);
    if (usedSlugs.has(q.slug)) throw new Error(`Cross-category duplicate: ${q.slug} in ${key}`);
    seen.add(q.slug);
    usedSlugs.add(q.slug);
  }

  if (questions.length !== 50) throw new Error(`${key}: expected 50, got ${questions.length}`);
  if (counts.Easy !== 20 || counts.Medium !== 20 || counts.Hard !== 10) {
    throw new Error(`${key}: bad distribution ${JSON.stringify(counts)}`);
  }

  dsaQuestions[key] = questions.map(({ slug, ...rest }) => rest);
}

const header = `/** AUTO-GENERATED by scripts/build-dsa-question-bank.mjs — do not edit manually */
export type DsaDifficulty = "Easy" | "Medium" | "Hard";
export type DsaQuestionTag = "must-do" | "frequent" | "advanced";

export type DsaQuestion = {
  title: string;
  difficulty: DsaDifficulty;
  url: string;
  tag?: DsaQuestionTag;
};

export type DsaCategoryKey =
  | "arrays"
  | "strings"
  | "linkedList"
  | "stackQueue"
  | "binarySearch"
  | "trees"
  | "heaps"
  | "graphs"
  | "dp"
  | "greedy"
  | "backtracking";

export type DsaCategory = {
  key: DsaCategoryKey;
  label: string;
  description: string;
};

export const DSA_CATEGORIES: DsaCategory[] = [
  { key: "arrays", label: "Arrays", description: "Two pointers, sliding window, prefix sums" },
  { key: "strings", label: "Strings", description: "Hashing, windows, pattern matching" },
  { key: "linkedList", label: "Linked List", description: "Pointers, reversal, cycle detection" },
  { key: "stackQueue", label: "Stack & Queue", description: "Monotonic stack, BFS-style queues" },
  { key: "binarySearch", label: "Binary Search", description: "Sorted arrays, search space reduction" },
  { key: "trees", label: "Trees", description: "Binary tree, BST traversals & validation" },
  { key: "heaps", label: "Heaps", description: "Priority queue, top-K patterns" },
  { key: "graphs", label: "Graphs", description: "DFS, BFS, topological sort" },
  { key: "dp", label: "Dynamic Programming", description: "1D/2D state, optimal substructure" },
  { key: "greedy", label: "Greedy", description: "Local choices, interval scheduling" },
  { key: "backtracking", label: "Backtracking", description: "Combinations, permutations, search" }
];

export const QUESTIONS_PER_CATEGORY = 50;
export const DIFFICULTY_DISTRIBUTION = { Easy: 20, Medium: 20, Hard: 10 } as const;

export const dsaQuestions: Record<DsaCategoryKey, DsaQuestion[]> = `;

const footer = `;

export function getCategoryDifficultyCounts(category: DsaCategoryKey) {
  const items = dsaQuestions[category];
  return {
    Easy: items.filter((q) => q.difficulty === "Easy").length,
    Medium: items.filter((q) => q.difficulty === "Medium").length,
    Hard: items.filter((q) => q.difficulty === "Hard").length,
    total: items.length
  };
}

export function getAllDsaQuestions(): Array<DsaQuestion & { category: DsaCategoryKey; categoryLabel: string }> {
  return DSA_CATEGORIES.flatMap((category) =>
    dsaQuestions[category.key].map((question) => ({
      ...question,
      category: category.key,
      categoryLabel: category.label
    }))
  );
}
`;

fs.writeFileSync(OUT, header + JSON.stringify(dsaQuestions, null, 2) + footer, "utf8");
console.log(`Wrote ${OUT} — ${Object.keys(dsaQuestions).length} categories, ${usedSlugs.size} unique questions`);

const MARGIN = 50;
const CONTENT_WIDTH = 495;
// Vertical space reserved at the bottom of every page for the footer band.
// Content auto-paginates before it reaches this zone so text never collides
// with the footer / page number.
const FOOTER_RESERVE = 58;
// Top of the content region on continuation pages — below the running header.
// Used both as the doc's top margin (so PDFKit's automatic text pagination
// resumes below the running header) and by drawRunningHeader.
const CONTENT_TOP = 70;

// Bottom edge of the writable content region on the current page.
function contentBottom(doc) {
  return doc.page.height - FOOTER_RESERVE;
}

function formatDateTime(date = new Date()) {
  const d = new Date(date);
  return {
    date: d.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" }),
    time: d.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true })
  };
}

function drawBrandMark(doc, x, y, size = 28) {
  if (fs.existsSync(LOGO_PATH)) {
    doc.image(LOGO_PATH, x, y, { width: size, height: size });
    return;
  }
  doc.save();
  doc.roundedRect(x, y, size, size, 6).fill(COLORS.primary);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(size * 0.38);
  doc.text("IA", x + size * 0.18, y + size * 0.28, { width: size * 0.64, align: "center" });
  doc.restore();
}

function drawHeader(doc, meta) {
  const { reportTitle, reportNumber, generatedBy, subject } = meta;
  const { date, time } = formatDateTime(meta.generatedAt);

  doc.save();
  doc.rect(0, 0, doc.page.width, 118).fill(COLORS.light);
  doc.restore();

  drawBrandMark(doc, MARGIN, 22, 32);
  doc.fillColor(COLORS.slate).font("Helvetica-Bold").fontSize(16);
  doc.text(BRAND_NAME, MARGIN + 42, 24);
  doc.fillColor(COLORS.muted).font("Helvetica").fontSize(9);
  doc.text(BRAND_TAGLINE, MARGIN + 42, 40, { width: 280 });
  doc.text(PORTAL_NAME, MARGIN + 42, 52, { width: 280 });

  // Compact verification pill (top-right) — replaces the old free-floating
  // badge that consumed a full-width vertical gap in the content flow.
  const pillWidth = 92;
  const pillX = MARGIN + CONTENT_WIDTH - pillWidth;
  doc.roundedRect(pillX, 24, pillWidth, 20, 10).fill(COLORS.primary);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(8);
  doc.text("VERIFIED REPORT", pillX, 30, { width: pillWidth, align: "center" });

  doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(18);
  doc.text(reportTitle, MARGIN, 72, { width: CONTENT_WIDTH - pillWidth - 10 });
  doc.fillColor(COLORS.slate).font("Helvetica").fontSize(9);
  doc.text(`Report Number: ${reportNumber}`, MARGIN, 98);
  doc.text(`Generated: ${date} at ${time}`, MARGIN + 220, 98);
  doc.text(`Generated By: ${generatedBy}`, MARGIN + 380, 98, { width: 150, align: "right" });

  if (subject?.name) {
    doc.fillColor(COLORS.muted).fontSize(8);
    doc.text(
      `${subject.role || "User"}: ${subject.name}${subject.email ? ` • ${subject.email}` : ""}`,
      MARGIN,
      108,
      { width: CONTENT_WIDTH }
    );
  }

  doc.moveTo(MARGIN, 128).lineTo(MARGIN + CONTENT_WIDTH, 128).strokeColor(COLORS.border).lineWidth(1).stroke();
  doc.y = 140;
}

// Compact header repeated on every continuation page so each printed sheet is
// self-identifying (brand + report number). Keeps the running content aligned
// with a consistent top margin.
function drawRunningHeader(doc, meta) {
  doc.save();
  drawBrandMark(doc, MARGIN, 26, 20);
  doc.fillColor(COLORS.slate).font("Helvetica-Bold").fontSize(11);
  doc.text(BRAND_NAME, MARGIN + 28, 28, { width: 200 });
  doc.fillColor(COLORS.muted).font("Helvetica").fontSize(8);
  doc.text(meta.reportTitle, MARGIN + 28, 41, { width: 240 });
  doc.fillColor(COLORS.muted).font("Helvetica").fontSize(8);
  doc.text(meta.reportNumber, MARGIN + CONTENT_WIDTH - 200, 34, { width: 200, align: "right" });
  doc.moveTo(MARGIN, 56).lineTo(MARGIN + CONTENT_WIDTH, 56).strokeColor(COLORS.border).lineWidth(0.5).stroke();
  doc.restore();
  doc.y = CONTENT_TOP;
}

// Creates a continuation page. The running header is drawn by the shared
// "pageAdded" handler (registered in generateEnterpriseReport), which also
// covers pages created by PDFKit's automatic text pagination.
function addContentPage(doc) {
  doc.addPage();
}

function sectionHeading(doc, title, number) {
  // Reserve enough for the heading, its rule, and at least one row of content
  // so a heading is never left stranded at the bottom of a page.
  ensureSpace(doc, 70);
  doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(12);
  doc.text(`${number}. ${title}`, MARGIN, doc.y, { width: CONTENT_WIDTH });
  doc.moveDown(0.35);
  doc.moveTo(MARGIN, doc.y).lineTo(MARGIN + CONTENT_WIDTH, doc.y).strokeColor(COLORS.border).lineWidth(0.5).stroke();
  doc.moveDown(0.6);
}

function ensureSpace(doc, height) {
  if (doc.y + height > contentBottom(doc)) {
    addContentPage(doc);
  }
}

function drawKeyValueTable(doc, rows) {
  const labelWidth = 160;
  const padX = 8;
  const padY = 6;
  const valueWidth = CONTENT_WIDTH - labelWidth - padX * 2;

  rows.forEach((row, index) => {
    const label = String(row[0] ?? "");
    const value = String(row[1] ?? "—");

    // Measure the value at the exact font it will be rendered with so tall
    // (wrapped) values get a proportionally taller row instead of overflowing.
    doc.font("Helvetica").fontSize(9);
    const valueHeight = doc.heightOfString(value, { width: valueWidth });
    const rowHeight = Math.max(22, valueHeight + padY * 2);

    ensureSpace(doc, rowHeight);
    const y = doc.y;

    doc.rect(MARGIN, y, CONTENT_WIDTH, rowHeight).fill(index % 2 === 0 ? "#ffffff" : COLORS.light);
    doc.fillColor(COLORS.muted).font("Helvetica-Bold").fontSize(9);
    doc.text(label, MARGIN + padX, y + padY, { width: labelWidth - padX });
    doc.fillColor(COLORS.slate).font("Helvetica").fontSize(9);
    doc.text(value, MARGIN + labelWidth + padX, y + padY, { width: valueWidth });

    doc.y = y + rowHeight; // deterministic advance — rows no longer overlap
  });
  doc.moveDown(0.6);
}

// Relative column weights (e.g. [2, 1, 1]) instead of an equal split. Longer
// text columns (names, notes) can be given more room so they wrap less and
// rows stay short — equal-width columns were forcing 3-line row heights on
// every row just because one column needed to wrap.
function computeColumnWidths(headers, weights) {
  const w = Array.isArray(weights) && weights.length === headers.length ? weights : headers.map(() => 1);
  const total = w.reduce((sum, x) => sum + x, 0);
  return w.map((x) => (CONTENT_WIDTH * x) / total);
}

function computeColumnX(colWidths) {
  const colX = [];
  let cursor = MARGIN;
  colWidths.forEach((width) => {
    colX.push(cursor);
    cursor += width;
  });
  return colX;
}

function drawTableHeaderRow(doc, headers, colX, colWidths) {
  const headerHeight = 24;
  const y = doc.y;
  doc.rect(MARGIN, y, CONTENT_WIDTH, headerHeight).fill(COLORS.primary);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(8);
  headers.forEach((header, i) => {
    doc.text(String(header), colX[i] + 6, y + 8, { width: colWidths[i] - 12 });
  });
  doc.y = y + headerHeight;
}

function drawDataTable(doc, headers, rows, weights) {
  const colWidths = computeColumnWidths(headers, weights);
  const colX = computeColumnX(colWidths);
  const minRowHeight = 22;

  ensureSpace(doc, 24 + minRowHeight);
  drawTableHeaderRow(doc, headers, colX, colWidths);

  rows.forEach((row, rowIndex) => {
    doc.font("Helvetica").fontSize(8);
    const cellHeights = row.map((cell, i) =>
      doc.heightOfString(String(cell ?? "—"), { width: colWidths[i] - 12 })
    );
    const rowHeight = Math.max(minRowHeight, ...cellHeights) + 8;

    // Break before drawing the row and repeat the header so continued tables
    // are never headerless or misaligned.
    if (doc.y + rowHeight > contentBottom(doc)) {
      addContentPage(doc);
      drawTableHeaderRow(doc, headers, colX, colWidths);
    }
    const y = doc.y;

    doc.rect(MARGIN, y, CONTENT_WIDTH, rowHeight).fill(rowIndex % 2 === 0 ? "#ffffff" : COLORS.light);
    doc.fillColor(COLORS.slate).font("Helvetica").fontSize(8);
    row.forEach((cell, colIndex) => {
      doc.text(String(cell ?? "—"), colX[colIndex] + 6, y + 6, { width: colWidths[colIndex] - 12 });
    });
    doc.y = y + rowHeight;
  });

  // Thin closing rule under the table for a finished, aligned look.
  doc.moveTo(MARGIN, doc.y).lineTo(MARGIN + CONTENT_WIDTH, doc.y).strokeColor(COLORS.border).lineWidth(0.5).stroke();
  doc.moveDown(0.7);
}

// Color-coded progress bar for 0..max scores (resume/ATS/skill-match/rating),
// replacing a plain "N/100" table row with an at-a-glance visual indicator.
function scoreBarColor(value, max) {
  const pct = max > 0 ? (value / max) * 100 : 0;
  if (pct >= 70) return COLORS.success;
  if (pct >= 40) return COLORS.warning;
  return COLORS.danger;
}

function drawScoreBar(doc, label, value, max = 100) {
  const rowHeight = 26;
  ensureSpace(doc, rowHeight + 4);
  const y = doc.y;
  const labelWidth = 150;
  const barX = MARGIN + labelWidth;
  const barWidth = CONTENT_WIDTH - labelWidth - 55;
  const barHeight = 10;
  const barY = y + 8;
  const safeValue = Math.max(0, Math.min(Number(value) || 0, max));

  doc.fillColor(COLORS.slate).font("Helvetica-Bold").fontSize(9);
  doc.text(label, MARGIN, y + 8, { width: labelWidth - 8 });

  doc.roundedRect(barX, barY, barWidth, barHeight, 5).fill(COLORS.border);
  const fillWidth = max > 0 ? (barWidth * safeValue) / max : 0;
  if (fillWidth > 0) {
    doc.roundedRect(barX, barY, Math.max(fillWidth, barHeight), barHeight, 5).fill(scoreBarColor(safeValue, max));
  }

  doc.fillColor(COLORS.slate).font("Helvetica-Bold").fontSize(9);
  doc.text(`${safeValue}/${max}`, barX + barWidth + 8, y + 7, { width: 47, align: "right" });

  doc.y = y + rowHeight;
}

// Truncates at the last whole word within maxLen instead of cutting mid-word
// (e.g. "...throughout the roun" -> "...throughout the…").
function truncateText(text, maxLen) {
  const value = String(text || "");
  if (value.length <= maxLen) return value;
  const cut = value.slice(0, maxLen);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > 0 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}

function bulletList(doc, items, emptyLabel = "No data available.") {
  const list = (items || []).filter(Boolean);
  if (!list.length) {
    doc.fillColor(COLORS.muted).font("Helvetica").fontSize(9);
    doc.text(emptyLabel, MARGIN, doc.y, { width: CONTENT_WIDTH });
    doc.moveDown(0.5);
    return;
  }
  const textWidth = CONTENT_WIDTH - 16;
  list.forEach((item) => {
    const text = String(item);
    doc.font("Helvetica").fontSize(9);
    const itemHeight = doc.heightOfString(text, { width: textWidth, lineGap: 2 });
    ensureSpace(doc, itemHeight + 4);
    const y = doc.y;
    doc.fillColor(COLORS.primary).text("•", MARGIN + 2, y, { width: 10 });
    doc.fillColor(COLORS.slate).text(text, MARGIN + 16, y, { width: textWidth, lineGap: 2 });
    doc.y = y + itemHeight;
    doc.moveDown(0.35);
  });
}

function drawExecutiveSummary(doc, summary) {
  sectionHeading(doc, "Executive Summary", 1);
  doc.fillColor(COLORS.slate).font("Helvetica").fontSize(10);
  const text = String(summary || "");
  const height = doc.heightOfString(text, { width: CONTENT_WIDTH, align: "justify", lineGap: 3 });
  ensureSpace(doc, Math.min(height, contentBottom(doc) - doc.y) + 4);
  doc.text(text, MARGIN, doc.y, { width: CONTENT_WIDTH, align: "justify", lineGap: 3 });
  doc.moveDown(0.9);
}

// Faint enough to never compete with real content for attention (Stripe/Notion-
// style restraint) — biased toward the lower half of the page since section
// headings and table headers tend to sit higher up.
function drawWatermark(doc) {
  const centerY = doc.page.height * 0.62;
  doc.save();
  doc.rotate(-32, { origin: [doc.page.width / 2, centerY] });
  doc.fillColor("#94a3b8").font("Helvetica-Bold").fontSize(40).opacity(0.045);
  doc.text(BRAND_NAME, 95, centerY - 26, { width: 400, align: "center" });
  doc.fontSize(12).opacity(0.035);
  doc.text(`${BRAND_NAME} Verified · ${BRAND_TAGLINE}`, 95, centerY + 16, {
    width: 400,
    align: "center"
  });
  doc.restore();
  doc.opacity(1);
}

// Footer band applied to every page in a single post-pass (needs the final
// page count for "Page X of Y"). The report number is printed here so every
// sheet is traceable — this replaces the former QR code, which only encoded
// the same report-number string and pointed at no resolvable resource.
function addFooters(doc, reportNumber) {
  const range = doc.bufferedPageRange();
  const total = range.count;
  for (let i = range.start; i < range.start + total; i += 1) {
    doc.switchToPage(i);

    // The footer + watermark are painted inside the bottom margin. If PDFKit
    // still enforces the page's content box while we do that, it treats the
    // write as an overflow and appends a stray blank page (and desyncs the
    // "Page X of Y" count). Zeroing the margins for this pass prevents that.
    doc.page.margins = { top: 0, bottom: 0, left: 0, right: 0 };

    drawWatermark(doc);

    const footerY = doc.page.height - 40;
    doc.moveTo(MARGIN, footerY - 8).lineTo(MARGIN + CONTENT_WIDTH, footerY - 8)
      .strokeColor(COLORS.border).lineWidth(0.5).stroke();
    doc.fillColor(COLORS.muted).font("Helvetica").fontSize(7);
    doc.text(`${BRAND_NAME} • Confidential Report • Ref: ${reportNumber} • v${REPORT_VERSION}`, MARGIN, footerY, {
      width: CONTENT_WIDTH - 120,
      lineBreak: false
    });
    doc.text(`Page ${i - range.start + 1} of ${total}`, MARGIN, footerY, {
      width: CONTENT_WIDTH,
      align: "right",
      lineBreak: false
    });
  }
}


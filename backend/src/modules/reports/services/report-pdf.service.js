async function generateEnterpriseReport({ code, generatedBy, subject, data }) {
  const definition = REPORT_DEFINITIONS[code];
  if (!definition) throw new AppError(`Unknown report code: ${code}`, 500);

  const reportNumber = await generateReportNumber(code);
  const generatedAt = new Date();

  // Bottom margin reserves the footer band so free-flowing text (summaries,
  // evaluations, bullet lists) auto-paginates before it can collide with the
  // footer or spill off the page.
  const doc = new PDFDocument({
    size: "A4",
    margins: { top: CONTENT_TOP, bottom: FOOTER_RESERVE + 4, left: MARGIN, right: MARGIN },
    bufferPages: true
  });
  const chunks = [];

  // Stamp a running header on every page after the first — including pages
  // created by PDFKit's automatic text pagination.
  doc.on("pageAdded", () => {
    if (doc._reportMeta) drawRunningHeader(doc, doc._reportMeta);
  });

  return new Promise((resolve, reject) => {
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", async () => {
      try {
        resolve({
          buffer: Buffer.concat(chunks),
          reportNumber,
          filename: `${reportNumber}.pdf`
        });
      } catch (error) {
        reject(error);
      }
    });
    doc.on("error", reject);

    (async () => {
      const meta = {
        reportTitle: definition.title,
        reportType: definition.title,
        reportNumber,
        generatedBy,
        generatedAt,
        subject
      };
      // Consumed by addContentPage() to stamp a running header on every
      // continuation page.
      doc._reportMeta = meta;

      drawHeader(doc, meta);
      drawExecutiveSummary(doc, definition.executiveSummary);

      const builder = CONTENT_BUILDERS[code];
      if (builder) builder(doc, data);

      // Signature block — keep the label and line together on one page.
      ensureSpace(doc, 96);
      doc.moveDown(1);
      doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(12);
      doc.text("Authorized Signature", MARGIN, doc.y, { width: CONTENT_WIDTH });
      doc.moveDown(2.2);
      const signatureLineY = doc.y;
      doc.moveTo(MARGIN, signatureLineY).lineTo(MARGIN + 180, signatureLineY)
        .strokeColor(COLORS.slate).lineWidth(0.75).stroke();
      doc.fillColor(COLORS.muted).font("Helvetica").fontSize(8);
      doc.text("Authorized Signatory", MARGIN, signatureLineY + 6);
      doc.text(`${BRAND_NAME} Platform`, MARGIN, signatureLineY + 18);

      addFooters(doc, reportNumber);
      doc.end();
    })().catch(reject);
  });
}

